def lemmatize_text_with_nltk(text: str) -> str:
    """Lemmatize text using NLTK.

    Args:
        text (str): Input text

    Returns:
        str: Lemmatized text

    """
    lemmatizer = WordNetLemmatizer()
    tokens = word_tokenize(text)
    lemmatized_sentence = [lemmatizer.lemmatize(token) for token in tokens]
    return " ".join(lemmatized_sentence)


def extract_artist_names(descriptions: list[str], channel_names: list[str]) -> set[str]:
    """Collect artist names from YouTube auto-generated descriptions and channel names.

    Returns the raw names plus their non-English words, lowercased, minus config.custom_keepwords.
    """
    yt_generated_regex = r"Provided to YouTube by (?P<company>.+)\n\n(?P<title>[^·]+) · (?P<authors>.+)\n\n(?P<album>.*)|Producer:\s(?P<producer>.+)|Composer:\s(?P<composer>.+)"
    artists = set()

    for x in descriptions:
        if "Auto-generated by YouTube.".lower() not in x.lower():
            continue
        m = re.findall(yt_generated_regex, x)
        if m:
            for x in m:
                if x[0]:  # company
                    artists.add(x[0])
                if x[2]:  # authors
                    authors = x[2].split("·")
                    authors = [author.strip() for author in authors]
                    for author in authors:
                        artists.add(author.lower())
                if x[4]:  # producers
                    artists.add(x[4])
                if x[5]:  # composers
                    artists.add(x[5])

    for channel in channel_names:
        artists.add(channel)

    english_words = set(words.words())

    def is_english_word(word: str) -> bool:
        if word.lower() in english_words:
            return True
        lemma = lemmatize_text_with_nltk(word)
        return lemma.lower() in english_words

    cleaned_artists = set()
    for x in list(artists):
        text = re.sub(
            r"[^a-zA-Z0-9\s\u4e00-\u9fff\uac00-\ud7af\u0900-\u097f\u0a00-\u0a7f\u0b00-\u0b7f\u0c00-\u0c7f\u0d00-\u0d7f\u0e00-\u0e7f]",
            " ",
            x,
        )
        text = re.sub(r"\s+", " ", text)
        text = re.sub(r" - Topic", " ", text)
        text = text.lower()
        text = text.strip()
        cleaned_artists.add(text)

    filtered_artist_names = set()
    for x in cleaned_artists:
        for w in x.split():
            if not is_english_word(w):
                filtered_artist_names.add(w)

    filtered_artist_names = filtered_artist_names - set(custom_keepwords)
    filtered_artist_names.update(artists)
    filtered_artist_names.discard("")
    return filtered_artist_names


def extract_artist_tokens(artist_names: set[str]) -> set[str]:
    """Return the cleaned single-word artist names, for the TF-IDF vectorizers to keep out of their vocabularies.

    Words that expand_contractions rewrites (ft, prod, vo, ...) are skipped: excluding their expansion would drop
    featuring, producer or vocalist everywhere.
    """
    artist_tokens = set()
    for name in artist_names:
        word = name.lower()
        if not re.fullmatch(r"\w+", word) or TextPreprocessor.expand_contractions(word) != word:
            continue
        cleaned_tokens = clean_text(word).split()
        if len(cleaned_tokens) == 1:
            artist_tokens.add(cleaned_tokens[0])
    return artist_tokens


def augment_text_with_synonyms(text: str, percentage: float = 0.1) -> str:
    words = text.split()
    num_words_to_change = int(len(words) * percentage)
    randomly_selected_words = random.sample(words, num_words_to_change)
    augmented_words = []

    for _, word in enumerate(words):
        if word in randomly_selected_words:
            synonyms = []
            for syn in wordnet.synsets(word):
                if syn is not None:
                    for lemma in syn.lemmas():
                        synonym = lemma.name().replace("_", " ").lower()
                        if synonym.isalpha():
                            synonyms.append(synonym)
            new_word = random.choice(synonyms) if synonyms else word
            augmented_words.append(new_word)
            continue
        augmented_words.append(word)

    return " ".join(augmented_words).lower()


SIMILARITY_BLOCK_ROWS = 1000


class DatasetPreprocessor:
    @staticmethod
    def remove_similar_rows(df: pd.DataFrame, threshold: float = 0.9) -> pd.DataFrame:
        """Remove rows with similar content based on TF-IDF similarity."""
        vectorizer = TfidfVectorizer()
        title_description = df["Title"] + " " + df["Description"]
        tfidf_matrix = vectorizer.fit_transform(title_description)
        labels = df["Is Music"].to_numpy(dtype=object)
        has_label = np.array([label is not None for label in labels])
        rows_to_remove = set()

        # The full similarity matrix is 8 * n^2 bytes (20 GB at 50k rows), so compare one block of rows at a time.
        for start in range(0, tfidf_matrix.shape[0], SIMILARITY_BLOCK_ROWS):
            block = cosine_similarity(tfidf_matrix[start : start + SIMILARITY_BLOCK_ROWS], tfidf_matrix)
            rows, columns = np.nonzero(block >= threshold)
            rows += start
            is_duplicate = (columns > rows) & has_label[rows] & has_label[columns] & (labels[rows] == labels[columns])
            rows_to_remove.update(df.index[columns[is_duplicate]])

        new_df = df.drop(index=list(rows_to_remove)).reset_index(drop=True)
        return new_df


def generate_new_pipeline(*, verbose: bool = True) -> Pipeline:
    def wrapper(func: Callable) -> Callable:
        return FunctionTransformer(lambda x: x.apply(func), validate=False)

    steps = [(name, wrapper(step)) for name, step in TEXT_CLEANING_STEPS]
    pipe = Pipeline(
        [*steps, ("convert_to_dataframe", FunctionTransformer(lambda x: pd.DataFrame(x)))],
        verbose=verbose,
    )
    return pipe
